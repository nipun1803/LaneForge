#!/usr/bin/env python3
"""Draw Fig. 5 of the report (vector-add waveform) from a real simulation VCD.

    make demo                                   # writes sim/run_programs.vcd
    python3 scripts/vcd_to_tikz.py sim/run_programs.vcd docs/report/fig_waveform.tex

Standard library only. Reads the signals of run_programs.u_add (the vector-add
program from programs/add.hex) and writes a TikZ timing diagram that splits the
ALU result into its four 8-bit lanes, so the reader can see all lanes change on
the same clock edge.
"""
import sys

T_END = 60          # ns of simulation to draw (reset + 5 instructions)
NS = 0.205          # cm per ns
SCOPE = "u_add"

MNEMONIC = {0xC: "VLD", 0xD: "VST", 0x1: "VADD", 0xF: "HALT"}


def parse_vcd(path):
    """Return {signal name: [(time, int value), ...]} for vars directly in SCOPE."""
    ids, changes, stack, t = {}, {}, [], 0
    with open(path) as f:
        tokens = iter(f.read().split())
    for tok in tokens:
        if tok == "$scope":
            next(tokens); stack.append(next(tokens))
        elif tok == "$upscope":
            stack.pop()
        elif tok == "$var":
            _, _, code, name = next(tokens), next(tokens), next(tokens), next(tokens)
            if stack and stack[-1] == SCOPE:
                ids.setdefault(code, name)
        elif tok.startswith("#"):
            t = int(tok[1:]) // 1000            # timescale 1ps -> ns
        elif tok[0] in "01xz" and tok[1:] in ids:
            changes.setdefault(ids[tok[1:]], []).append((t, int(tok[0]) if tok[0] in "01" else None))
        elif tok[0] == "b":
            code = next(tokens)
            if code in ids:
                bits = tok[1:]
                val = None if any(c in "xz" for c in bits) else int(bits, 2)
                changes.setdefault(ids[code], []).append((t, val))
    return changes


def segments(ch):
    """Collapse a change list into (start, end, value) segments up to T_END."""
    out = []
    for i, (t, v) in enumerate(ch):
        end = ch[i + 1][0] if i + 1 < len(ch) else T_END
        if t >= T_END:
            break
        if out and out[-1][2] == v:
            out[-1] = (out[-1][0], min(end, T_END), v)
        else:
            out.append((t, min(end, T_END), v))
    return out


def x(t):
    return f"{t * NS:.3f}"


def bus(y, segs, fmt, style="bus"):
    lines = []
    for a, b, v in segs:
        if b <= a:
            continue
        s = 0.12 if b - a > 2 else 0
        lines.append(
            f"\\draw[{style}] ({x(a)},{y}) -- ({x(a)}+{s},{y}+0.17) -- ({x(b)}-{s},{y}+0.17) -- ({x(b)},{y})"
            f" -- ({x(b)}-{s},{y}-0.17) -- ({x(a)}+{s},{y}-0.17) -- cycle;")
        if v is not None and b - a >= 6:
            lines.append(f"\\node[val] at ({(a + b) / 2 * NS:.3f},{y}) {{{fmt(v)}}};")
    return lines


def bit(y, segs, color):
    pts = []
    for a, b, v in segs:
        lvl = 0.17 if v else -0.17
        pts += [f"({x(a)},{y}{lvl:+.2f})", f"({x(b)},{y}{lvl:+.2f})"]
    return [f"\\draw[thick, {color}] " + " -- ".join(pts) + ";"]


def main(vcd, out):
    c = parse_vcd(vcd)
    lane = lambda k: [(t, None if v is None else (v >> (8 * k)) & 0xFF) for t, v in c["vy"]]
    instr_txt = lambda v: f"{MNEMONIC.get(v >> 12, '?')} \\texttt{{{v:04X}}}"

    rows = [  # (label, kind, data, extra)
        ("clk", "bit", c["clk"], "black"),
        ("pc", "bus", c["pc"], lambda v: str(v)),
        ("instr", "bus", c["instr"], instr_txt),
        ("vs1 (rdata1)", "bus", c["rdata1"], lambda v: f"\\texttt{{{v:08X}}}"),
        ("operand B (vb)", "bus", c["vb"], lambda v: f"\\texttt{{{v:08X}}}"),
    ] + [(f"lane {k} result", "lane", lane(k), lambda v: str(v)) for k in range(4)] + [
        ("rf\\_we", "bit", c["rf_we_g"], "cStore!80!black"),
        ("mem\\_we", "bit", c["mem_we_g"], "cMem!90!black"),
        ("halted", "bit", c["halted"], "cFail!85!black"),
    ]

    # VADD cycle: the interval during which instr == VADD
    iv = segments(c["instr"])
    vadd = next((a, b) for a, b, v in iv if v is not None and v >> 12 == 0x1)

    L = [
        "% Generated by scripts/vcd_to_tikz.py from sim/run_programs.vcd - do not edit by hand",
        "\\begin{tikzpicture}[font=\\scriptsize,",
        "  bus/.style={draw=cFetch!75!black, fill=cFetch!10, thin},",
        "  lanebus/.style={draw=cComp!80!black, fill=cComp!18, thin},",
        "  val/.style={font=\\tiny, inner sep=0}]",
    ]
    n = len(rows)
    top, bottom = 0.45, -(n - 1) * 0.5 - 0.35
    L.append(f"\\fill[cComp!12] ({x(vadd[0])},{top}) rectangle ({x(vadd[1])},{bottom});")
    L.append(f"\\node[font=\\scriptsize\\bfseries, text=cComp!80!black, anchor=south] at "
             f"({(vadd[0] + vadd[1]) / 2 * NS:.3f},{top}) {{VADD: 4 lanes, 1 cycle}};")
    for t in range(5, T_END, 10):  # rising edges
        L.append(f"\\draw[gray!35, densely dotted] ({x(t)},{top}) -- ({x(t)},{bottom});")
    for i, (label, kind, data, extra) in enumerate(rows):
        y = f"{-i * 0.5:.2f}"
        L.append(f"\\node[anchor=east, font=\\scriptsize] at (-0.1,{y}) {{{label}}};")
        segs = segments(data)
        if kind == "bit":
            L += bit(y, segs, extra)
        else:
            L += bus(y, segs, extra, "lanebus" if kind == "lane" else "bus")
    L.append(f"\\draw[-{{Latex[length=1.5mm]}}, gray] (0,{bottom}) -- ({x(T_END)}+0.2,{bottom}) "
             f"node[right, font=\\tiny] {{ns}};")
    for t in range(0, T_END + 1, 10):
        L.append(f"\\node[font=\\tiny, gray, below] at ({x(t)},{bottom}) {{{t}}};")
    L.append("\\end{tikzpicture}")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {out} (VADD at {vadd[0]}-{vadd[1]} ns)")


if __name__ == "__main__":
    main(*sys.argv[1:3])
